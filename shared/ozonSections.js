// Разделы кабинета продавца Ozon и разбор метки уведомления. Вынесено из
// src/utils/navigators/ozonNavigate.js: это ОБЩИЕ данные и чистые расчёты (адреса разделов, разбор
// метки, подготовка строки для поиска) — они не про интерфейс, поэтому лежат в shared/ и не занимают
// бюджет строк экранов (правило проекта ADR-044).
//
// ЗАЧЕМ ЭТО ВООБЩЕ НУЖНО. Уведомления Ozon бывают трёх видов: сообщение покупателя, вопрос к товару
// и отзыв. Живут они в РАЗНЫХ разделах кабинета. Раньше переход по нажатию на уведомление искал
// что угодно среди строк переписок — вопроса там нет в принципе, и человек всегда видел красное
// «… — не найден в списке» (разбор 2026-09-24, находка ревью #13).

/** Адреса разделов. Те же, что открывает быстрый виджет Ozon (src/native/components/OzonQuickWidget.jsx). */
export const OZON_SECTION_URL = {
  q: 'https://seller.ozon.ru/app/reviews/questions',
  rv: 'https://seller.ozon.ru/app/reviews',
  list: 'https://seller.ozon.ru/app/messenger',
}

/**
 * Какой раздел открывать — по метке уведомления. Метку ставит сторож страницы
 * (main/preloads/hooks/ozon.hook.js) и она доезжает до нажатия как chatTag.
 * @param {string} chatTag — `ozon-q:<отпечаток>` (вопрос) / `ozon-rv:<…>` (отзыв) / `ozon-list:<…>` (чат)
 * @returns {'q'|'rv'|'list'} метки нет или она чужая → считаем чатом, как было до v1.2.499
 */
export function ozonSectionOf(chatTag) {
  const t = String(chatTag || '')
  if (t.startsWith('ozon-q:')) return 'q'
  if (t.startsWith('ozon-rv:')) return 'rv'
  return 'list'
}

/**
 * Сколько первых символов названия сравнивать при поиске строки.
 *
 * ПОЧЕМУ НЕ ЦЕЛИКОМ: у вопроса и отзыва «отправитель» — это название товара. Оно длинное, в
 * уведомлении обрезано многоточием, а на странице может переноситься и склеиваться пробелами —
 * совпадение строки целиком недостижимо.
 */
export const OZON_MATCH_LEN = 25

/** Начало названия для поиска: без лишних пробелов и без хвостового многоточия из уведомления. */
export function ozonNeedle(senderName) {
  return String(senderName || '').replace(/\s+/g, ' ').replace(/[.…\s]+$/, '').trim().slice(0, OZON_MATCH_LEN)
}
