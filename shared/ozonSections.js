// shared/ozonSections.js — v1.2.500
//
// Разделы кабинета продавца Ozon и разбор метки уведомления. Общие данные и чистые расчёты —
// лежат в shared/ и не занимают бюджет строк экранов (правило проекта ADR-044).
//
// ЗАЧЕМ. Уведомления Ozon бывают трёх видов: сообщение покупателя, вопрос к товару и отзыв.
// Живут они в РАЗНЫХ разделах кабинета, поэтому переход по нажатию обязан знать, куда идти.

/**
 * Адреса разделов. Те же, что открывает быстрый виджет Ozon (src/native/components/OzonQuickWidget.jsx)
 * и фоновые страницы (src/App.jsx) — включая подраздел покупателей у «Сообщений»: без него
 * открывается не тот список (найдено ревью v1.2.499).
 */
export const OZON_SECTION_URL = {
  q: 'https://seller.ozon.ru/app/reviews/questions',
  rv: 'https://seller.ozon.ru/app/reviews',
  list: 'https://seller.ozon.ru/app/messenger?group=customers_v2',
}

/** Путь раздела без имени сайта и без параметров — для ТОЧНОГО сравнения «мы уже здесь?». */
export const OZON_SECTION_PATH = {
  q: '/app/reviews/questions',
  rv: '/app/reviews',
  list: '/app/messenger',
}

/**
 * Какой раздел открывать — по метке уведомления. Метку ставит сторож страницы
 * (main/preloads/hooks/ozon.hook.js) и она доезжает до нажатия как chatTag.
 * @param {string} chatTag — `ozon-q:<отпечаток>` (вопрос) / `ozon-rv:<…>` (отзыв) / `ozon-list:<…>` (чат)
 * @returns {'q'|'rv'|'list'} метки нет или она чужая → считаем чатом покупателя
 */
export function ozonSectionOf(chatTag) {
  const t = String(chatTag || '')
  if (t.startsWith('ozon-q:')) return 'q'
  if (t.startsWith('ozon-rv:')) return 'rv'
  return 'list'
}

/**
 * 🔴 ЛОВУШКА (ревью v1.2.499, исправлено в v1.2.500): сравнивать раздел ПОДСТРОКОЙ нельзя —
 * путь отзывов `/app/reviews` целиком входит в путь вопросов `/app/reviews/questions`.
 * Из-за этого, стоя на странице «Вопросы», программа считала, что она уже в «Отзывах», и
 * никуда не переходила. Сравниваем ТОЧНО, с точностью до завершающей косой черты.
 * @param {string} pathname — location.pathname текущей страницы
 * @param {'q'|'rv'|'list'} section
 */
export function ozonHereAlready(pathname, section) {
  const want = OZON_SECTION_PATH[section]
  if (!want) return false
  const p = String(pathname || '').replace(/\/+$/, '')
  return p === want
}

/**
 * Название товара для поиска строки: чистим пробелы и хвостовое многоточие.
 *
 * 🔴 ЛОВУШКА (ревью v1.2.499, исправлено в v1.2.500): раньше здесь обрезалось до 25 символов, и у
 * товаров одной линейки («Ремень генератора Contitech 10PK1555» и «…10PK1600») строка поиска
 * получалась ОДИНАКОВОЙ — открывался чужой товар, причём с отчётом «успех». Название приходит в
 * уведомление ЦЕЛИКОМ (сторож берёт textContent ссылки), многоточие рисует только оформление —
 * значит резать его нам незачем. Короткий запасной вариант — ниже, в ozonNeedleShort.
 */
export function ozonNeedle(senderName) {
  return String(senderName || '').replace(/\s+/g, ' ').replace(/[.…\s]+$/, '').trim()
}

/** Сколько символов берёт ЗАПАСНОЙ короткий поиск, если по полному названию ничего не нашлось. */
export const OZON_MATCH_LEN = 40

/** Запасное начало названия — на случай, если на странице текст записан иначе (перенос, лишний знак). */
export function ozonNeedleShort(senderName) {
  return ozonNeedle(senderName).slice(0, OZON_MATCH_LEN)
}

/**
 * Адреса ФОНОВЫХ страниц Ozon в том порядке, в котором их открывает src/App.jsx.
 * 🔴 ПОРЯДОК ВАЖЕН: по номеру страницы там выбирается частота обновления и признак «не шуметь
 * об ошибке» (0 — вопросы раз в минуту, 2 — отзывы раз в три минуты). Менять порядок нельзя,
 * не поправив те настройки.
 */
export const OZON_BG_URLS = [OZON_SECTION_URL.q, OZON_SECTION_URL.list, OZON_SECTION_URL.rv]

/**
 * Предел числа на значке быстрого виджета Ozon: до него показываем точное число, дальше — «50+».
 *
 * ПОЧЕМУ 50, а не общие для программы 99 (так у вкладок мессенджеров и бокового рейла —
 * src/components/MessengerTab.jsx, src/native/components/RailWebIcon.jsx): в кабинете продавца
 * счёт идёт не по чатам, а по отзывам, вопросам и сообщениям покупателей — их бывают сотни, и
 * точная цифра выше полусотни работе не помогает. Просьба пользователя от 2026-09-25:
 * «видеть последние 50, а если больше — писать 50+».
 *
 * 🔴 ВАЖНО ЗНАТЬ, ГЛЯДЯ НА ЭТОТ ЗНАЧОК: сам счёт пока НЕПОЛНЫЙ — сторож видит только ту часть
 * списка, которую Ozon успел нарисовать (разбор — features.md v1.2.502, ловушка «счётчик по
 * строкам разметки считает только нарисованную порцию»). Поэтому до починки счёта «50+» на
 * значке практически не появится. Предел ставим заранее, чтобы после починки ничего не забыть.
 */
export const OZON_BADGE_MAX = 50

/**
 * Что писать на значке: точное число либо «50+».
 * @param {number} n — сколько новых насчитал сторож
 * @returns {string} мусор и отрицательные значения считаем нулём (значок с «NaN» — хуже пустого)
 */
export function ozonBadgeText(n) {
  const v = Number(n)
  if (!Number.isFinite(v) || v <= 0) return '0'
  return v > OZON_BADGE_MAX ? OZON_BADGE_MAX + '+' : String(Math.floor(v))
}

/**
 * Сколько вопросов Ozon показывает в списке за раз. Доказано журналом: сторож видит ровно 11 строк
 * (10 вопросов + шапка таблицы) при любом числе вопросов — дальше кнопка «Показать ещё».
 */
export const OZON_QA_PAGE = 10

/**
 * Что писать на значке «Вопросы»: сколько вопросов БЕЗ ОТВЕТА.
 *
 * v1.2.507, по прямому указанию пользователя: «почему стоит 1, если 4 вопроса без ответа?».
 * В v1.2.506 значок показывал число со вкладки «Новое» (сколько вопросов не открывали) — оно точное,
 * но в работе бесполезное: отвечать надо на те, где ответа нет, а открыт вопрос или нет — неважно.
 *
 * 🔴 ЧЕСТНОСТЬ ЧИСЛА. «Без ответа» считает наш сторож по видимым строкам, а видит он первую порцию
 * (десять). Поэтому, когда вопросов в разделе больше порции, к числу добавляется «+»: «4+» читается
 * как «минимум четыре, возможно больше». Без этого значка человек думал бы, что их ровно четыре.
 * Готового счётчика «без ответа» у Ozon нет вовсе: вкладки считают «просмотрено», а не «отвечено».
 *
 * @param {number} unans — сколько без ответа среди видимых строк
 * @param {number|null} total — сколько вопросов в разделе всего (вкладка «Все»); null = неизвестно
 */
export function ozonQaBadgeText(unans, total) {
  const v = Number(unans)
  if (!Number.isFinite(v) || v <= 0) return '0'
  if (v > OZON_BADGE_MAX) return OZON_BADGE_MAX + '+'
  const all = Number(total)
  // Ноль здесь означает «сколько всего — не знаем» (виджет подставляет 0, когда числа ещё нет).
  // В таком случае плюс СТАВИМ: мы заведомо видим лишь первую порцию, и промолчать было бы враньём.
  const partial = !Number.isFinite(all) || all <= 0 || all > OZON_QA_PAGE
  return Math.floor(v) + (partial ? '+' : '')
}

/**
 * Подсказка при наведении на значок быстрого виджета Ozon.
 *
 * v1.2.507: живёт здесь, рядом с подписями значков, а не в самом виджете — во-первых, тут ей место
 * (одно решение — один файл), во-вторых, бюджет строк экранов (ADR-044) не позволяет наращивать
 * renderer, а общая папка в него не входит.
 *
 * У «Вопросов» подсказка объясняет ДВА числа Ozon, которые легко перепутать:
 *   • «без ответа» — на что надо отвечать (считает наш сторож по видимым строкам, поэтому «+»);
 *   • «не открыто» — вкладка «Новое» самого Ozon, сколько вопросов человек ещё не открывал.
 *
 * @param {'msg'|'qa'|'rv'} key — раздел
 * @param {string} label — его название («Вопросы»)
 * @param {number} n — число на значке
 * @param {{qaNew?: number, qaTotal?: number}} extra — вторые числа раздела «Вопросы»
 */
export function ozonTipText(key, label, n, extra) {
  const name = String(label || '')
  if (key !== 'qa') return name + (n > 0 ? ' · ' + n + ' новых' : '')
  const parts = []
  const total = Number(extra && extra.qaTotal) || 0
  if (n > 0) parts.push(n + ' без ответа' + (total > OZON_QA_PAGE ? ' (среди первых ' + OZON_QA_PAGE + ', всего ' + total + ')' : ''))
  const fresh = Number(extra && extra.qaNew) || 0
  if (fresh > 0) parts.push('не открыто: ' + fresh)
  return name + (parts.length ? ' · ' + parts.join(' · ') : '')
}
