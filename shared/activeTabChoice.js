/**
 * Какую вкладку сделать активной после загрузки списка мессенджеров.
 *
 * @param {string|null|undefined} prevId — вкладка, выбранная СЕЙЧАС (null при первом запуске)
 * @param {Array<{id: string}>} messengers — итоговый список вкладок (веб + нативная)
 * @param {string} nativeId — идентификатор нативной вкладки «ЦентрЧатов»
 * @returns {string|null} идентификатор вкладки, которую показать
 *
 * Правила по порядку:
 *  1. выбранная вкладка существует в списке → оставляем её (не отбираем у пользователя);
 *  2. иначе есть нативная вкладка → «ЦентрЧатов» (стартовое поведение v1.2.399);
 *  3. иначе первая вкладка списка;
 *  4. список пуст → null.
 *
 * Крайние случаи: `prevId` указывает на удалённую вкладку → пункт 1 не срабатывает,
 * уходим на «ЦентрЧатов» (иначе остались бы на несуществующей вкладке с пустым экраном);
 * `messengers` не массив / пустой → null.
 */
export function pickActiveTabId(prevId, messengers, nativeId) {
  const list = Array.isArray(messengers) ? messengers : []
  if (prevId && list.some(m => m && m.id === prevId)) return prevId
  if (nativeId && list.some(m => m && m.id === nativeId)) return nativeId
  // Берём первую ЖИВУЮ запись, а не list[0]: битый элемент в начале списка не должен
  // приводить к «вкладка не выбрана» (пустой экран). Поймано тестом крайних случаев.
  const first = list.find(m => m && m.id)
  return (first && first.id) || null
}
