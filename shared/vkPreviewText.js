/**
 * v1.2.477 — ЧИСТКА ПОДПИСИ СТРОКИ СПИСКА ЧАТОВ ВК от собственной пометки вложения.
 *
 * ── ЖАЛОБА (2026-09-18) ──────────────────────────────────────────────────────
 * В карточке уведомления ВК приходил лишний хвост:
 *   • ответ на сообщение → «Вот пишу тебе сообщение 😇🫶 Сообщение»
 *   • фото с подписью    → «Так пойдёт? Фотография»
 *   • фото без подписи   → «Фотография»
 * Пользователь: слово в конце лишнее, а фото хочется видеть фотографией.
 *
 * ── ОТКУДА ХВОСТ (измерено, не догадка) ──────────────────────────────────────
 * Это пишет САМ ВК в строке списка чатов, а наш перехватчик копирует подпись
 * целиком. Доказано журналом этой же сессии:
 *   11:10:13 «Вот пишу тебе сообщение 😇🫶 Сообщение»
 *   11:11:07 «Фотография»
 *   11:12:45 «Так пойдёт? Фотография»
 * — то есть пометка уже была в тексте, который дал ВК, до всякой нашей обработки.
 * Такая же пометка словом видна и у каналов ВК: разбор вёрстки v1.2.114 нашёл
 * элемент `ChannelPostPreview__attach` со значением «[Видео]».
 *
 * ── ПОЧЕМУ РЕЖЕМ ТЕКСТОМ, А НЕ ПО ВЁРСТКЕ ────────────────────────────────────
 * Резать по вёрстке (выкинуть элемент с классом «attach») надёжнее, но точный
 * класс строки ЛИЧНОГО чата на vk.ru неизвестен, а гадать по селекторам проект
 * уже пробовал пять раз подряд (v1.2.110–120) — каждый раз мимо.
 *
 * ── ЧТОБЫ НЕ СЪЕСТЬ ЖИВОЙ ТЕКСТ (грабля v1.2.115) ────────────────────────────
 * Тогда чистка «по словам» откусила хвост фразы «буду через 5 минут» → «буду
 * через». Поэтому здесь ЧЕТЫРЕ ограничителя сразу:
 *   1) пометка снимается ТОЛЬКО с самого конца строки;
 *   2) сверка С УЧЁТОМ РЕГИСТРА — ВК пишет пометку с большой буквы, а живая речь
 *      («удали это сообщение», «пришли фотографию») идёт с маленькой;
 *   3) пометка должна быть отдельным словом (перед ней пробел или начало строки);
 *   4) список пометок ЗАКРЫТЫЙ — это названия вложений ВК, а не любые слова.
 * Плюс результат никогда не пустой: если от текста осталась одна пометка, она и
 * остаётся (у фото — короткое «📷 Фото»), иначе карточку выбросил бы страж
 * пустого текста в главном процессе.
 */

/** Пометки-вложения, при которых сообщение — это фотография. */
export const VK_PHOTO_LABELS = ['Фотография', 'Фотографии', 'Изображение']

/**
 * Прочие пометки-вложения ВК. Длинные стоят раньше коротких не для красоты:
 * «Голосовое сообщение» обязано срезаться целиком, а не оставить «Голосовое».
 */
export const VK_OTHER_LABELS = [
  'Голосовое сообщение', 'Видеосообщение', 'Аудиосообщение', 'Аудиозапись', 'Видеозапись',
  'Сообщение', 'Документ', 'Граффити', 'Открытка', 'Подарок', 'История', 'Стикер',
  'Запись', 'Статья', 'Ссылка', 'Товар', 'Опрос', 'Карта', 'Место', 'Файл',
]

/** Счётные формы («3 фотографии», «2 сообщения») — они идут с маленькой буквы после числа. */
const COUNTED_PHOTO = /(^|\s)\d+\s+фотографи[йи]$/
const COUNTED_OTHER = /(^|\s)\d+\s+(сообщени[йя]|вложени[йя]|файла?|файлов)$/

/** Короткая замена, когда от сообщения с фотографией не осталось текста. */
export const VK_PHOTO_ONLY_TEXT = '📷 Фото'

/**
 * Снять с конца подписи пометку вложения ВК.
 *
 * @param {string} raw — подпись строки списка чатов, как её дал ВК
 * @returns {{text: string, label: string, photo: boolean}}
 *   text — что показывать (никогда не пустое, если было не пустым);
 *   label — какая пометка снята ('' если ничего не снимали);
 *   photo — снятая пометка означала фотографию.
 */
export function stripVkAttachLabel(raw) {
  const src = String(raw == null ? '' : raw).trim()
  if (!src) return { text: src, label: '', photo: false }

  let label = '', photo = false
  for (const cand of VK_PHOTO_LABELS) {
    if (endsWithWord(src, cand)) { label = cand; photo = true; break }
  }
  if (!label) {
    for (const cand of VK_OTHER_LABELS) {
      if (endsWithWord(src, cand)) { label = cand; break }
    }
  }
  if (!label) {
    const counted = src.match(COUNTED_PHOTO) || src.match(COUNTED_OTHER)
    if (counted) { label = counted[0].trim(); photo = !!src.match(COUNTED_PHOTO) }
  }
  if (!label) return { text: src, label: '', photo: false }

  const rest = src.slice(0, src.length - label.length).trim()
  // Осталась одна пометка: у фотографии показываем короткое «📷 Фото», у прочих
  // оставляем как было — пустая карточка всё равно не дошла бы до экрана.
  if (!rest) return { text: photo ? VK_PHOTO_ONLY_TEXT : src, label, photo }
  return { text: photo ? '📷 ' + rest : rest, label, photo }
}

/** Строка заканчивается этим словом (с учётом регистра) и слово отдельное? */
function endsWithWord(src, word) {
  if (!src.endsWith(word)) return false
  const before = src.length - word.length - 1
  return before < 0 || /\s/.test(src[before])
}
