// shared/panelWidthCap.js — v1.2.455
//
// ЗАЧЕМ: панель ИИ не должна быть шире, чем позволяет окно.
//
// ИСТОРИЯ. В v1.2.454 закрыли жалобу «окно чата уехало за границы»: растягивающейся
// середине разрешили сжиматься, и лишнее перестало уезжать за край. Но сохранённая
// ширина панели (у пользователя 458 точек) с размером окна ВСЁ РАВНО никак не
// сверялась — на ноутбуке 1280 или в узком окне панель заняла бы почти всё, а окно
// переписки сжалось бы до ничего. Это и есть «ограничить по-настоящему».
//
// ПОЧЕМУ ИМЕННО ТАК (а не слушатель размера окна):
//   • Слушатель размера — это новое хранилище внутри приложения (React-хук). Добавление
//     хука в РАБОТАЮЩЕЕ приложение ломает горячую перезагрузку («Should have a queue»,
//     см. v1.2.452) — мы это уже проходили дважды.
//   • Слушатель, записывающий ширину в настройки, УНИЧТОЖИЛ бы выбор пользователя:
//     свернул окно поменьше — и твои 458 навсегда стали 300.
//   • Правило вёрстки `min(458px, 50vw)` считает сам браузер при каждом изменении
//     размера окна: ноль слушателей, ноль хуков, ноль перерисовок, и сохранённое
//     число НЕ портится — окно вернули широким, панель снова 458.
//
// ФАКТЫ (уровень 1, MDN):
//   • `min()` — «lets you set the smallest value from a list of comma-separated
//     expressions», можно смешивать разные единицы (px и vw);
//   • `vw` — 1% ширины видимой области окна; пересчитывается при изменении размера;
//   • `min-width` при конфликте побеждает `max-width` — поэтому для внутреннего слоя
//     панели мы задаём ТО ЖЕ выражение, а не отдельный потолок.
//
// ⚠️ Ширину списка чатов здесь СПЕЦИАЛЬНО не ограничиваем — см. `code-todo.md` (TODO-40):
// «узкий» вид списка включается по числу из состояния, а не по реальной ширине; потолок
// из вёрстки рассогласовал бы их (панель узкая, а внутри рисуются широкие строки).

// Доля окна, шире которой панель ИИ не бывает. Половина — понятное пользователю
// правило: «панель никогда не больше половины окна».
export const AI_PANEL_MAX_WINDOW_SHARE = 0.5

// Потолок ручного растягивания (был и остаётся в перетаскивании панели).
export const AI_PANEL_MAX_PX = 600
export const AI_PANEL_MIN_PX = 240

/**
 * Предел ширины панели ИИ в точках для ТЕКУЩЕГО окна.
 * Нужен при перетаскивании: без него панель упиралась бы в невидимую стену
 * (тянешь — а она не растёт), потому что вёрстка её всё равно обрежет.
 * @param {number} windowWidth ширина окна (window.innerWidth)
 * @returns {number} предел в точках, не меньше минимальной ширины
 */
export function aiPanelMaxPx(windowWidth) {
  const byWindow = Number.isFinite(windowWidth) && windowWidth > 0
    ? Math.floor(windowWidth * AI_PANEL_MAX_WINDOW_SHARE)
    : AI_PANEL_MAX_PX
  // Нижняя граница — подстраховка «на всякий случай». На деле она не срабатывает
  // никогда: главное окно нельзя сузить меньше 900 точек (minWidth: 900 в
  // main/utils/windowManager.js), значит половина окна — минимум 450 > 240. Поэтому
  // предел перетаскивания и правило вёрстки всегда дают одно и то же число.
  return Math.max(AI_PANEL_MIN_PX, Math.min(AI_PANEL_MAX_PX, byWindow))
}

// 🔴 v1.2.456 (находка собственного ревью). ПОТОЛОК ДЛЯ ВНЕШНЕГО СЛОЯ ЗАДАЁТСЯ ОТДЕЛЬНО,
// а НЕ вписывается в саму ширину. Почему это важно: на ширину внешнего слоя панели навешен
// плавный переход 0.15с (`transition: width` в AISidebar.jsx — он делает красивое
// сворачивание). Если вписать потолок прямо в ширину, её вычисленное значение начинает
// меняться при каждом изменении размера окна → каждый раз запускается анимация, и край
// панели едет за краем окна с отставанием; в эти доли секунды ряд может не влезть
// (а он помечен «лишнее срезать»). Отдельное правило «максимальная ширина» в переход не
// входит, поэтому ширина остаётся постоянным числом и анимация запускается только там,
// где и задумано — при сворачивании панели.
// Факт уровня 1 (MDN, CSS transitions): переход срабатывает на изменение ВЫЧИСЛЕННОГО
// значения свойства; свойства `max-width` в списке перехода нет, значит его изменение
// анимацию не запускает.
export const AI_PANEL_MAX_CSS = `${Math.round(AI_PANEL_MAX_WINDOW_SHARE * 100)}vw`

/**
 * Значение ширины для ВНУТРЕННЕГО слоя панели: «столько, сколько просили, но не больше
 * половины окна», одним выражением.
 * Внутреннему слою нужен именно такой вид, а не отдельный потолок: у него задан ещё и
 * минимум ширины (чтобы содержимое не переливалось во время сворачивания), а по правилам
 * вёрстки минимум побеждает максимум — отдельный потолок там просто не сработал бы.
 * Перехода на внутреннем слое нет, поэтому отставания это не создаёт.
 * @param {number} px сохранённая (желаемая) ширина панели
 * @returns {string} например `min(458px, 50vw)`
 */
export function aiPanelWidthCss(px) {
  const want = Number.isFinite(px) && px > 0 ? Math.round(px) : AI_PANEL_MIN_PX
  const share = Math.round(AI_PANEL_MAX_WINDOW_SHARE * 100)
  return `min(${want}px, ${share}vw)`
}
