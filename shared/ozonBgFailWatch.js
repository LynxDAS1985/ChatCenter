import { decideOzonBgFailNotice } from './ozonNotifDedup.js'
import { RETRY_LADDER_MS, ERROR_PAGE_GRACE_MS } from './reconnectPlan.js'

/** Сколько ждём, прежде чем тревожить человека (за это время страница обычно успевает подняться). */
export const OZON_BG_FAIL_WAIT_MS = 45000
/** Меньше этого числа элементов — перед нами заглушка Chromium, а не Ozon (порог из ozon.hook.js). */
export const OZON_BG_ALIVE_MIN_NODES = 300

/**
 * Доказывает ли это сообщение сторожа, что открылся НАСТОЯЩИЙ Ozon?
 *
 * Пустая страница-ошибка Chromium тоже запускает наш сторож, поэтому годятся
 * только сообщения, для которых нужны реальные строки на странице.
 *
 * @param {{type:string, n:*}} parsed — разобранное сообщение (consoleMessageParser)
 * @returns {boolean}
 */
export function isOzonAliveProof(parsed) {
  if (!parsed) return false
  if (parsed.type === 'notification') return true          // уведомление строят из найденной строки
  return parsed.type === 'ozon_count' && Number(parsed.n) > 0 // счётчик > 0 = строки реально есть
}

/**
 * Сторож «подожди и посмотри» для ОДНОЙ фоновой страницы Ozon.
 *
 * Живёт в общем коде, а не в интерфейсе: это чистая логика без DOM, а у
 * интерфейса общий бюджет строк (правило проекта — выносить такое в `shared/`).
 *
 * @param {object} deps
 * @param {Function} deps.log      — запись в журнал (уровень, текст)
 * @param {Function} deps.notify   — показать карточку пользователю
 * @param {Function} deps.reload   — перезагрузить страницу
 * @param {Function} deps.alive    — жива ли сама страница (false = её убрали с экрана)
 * @param {Function} deps.probe    — спросить у страницы число элементов (обещание с числом)
 * @param {boolean}  deps.suppress — раздел, который не тревожит пользователя («Отзывы»)
 * @returns {{onFail:Function, onLoaded:Function, onHookProof:Function, stop:Function}}
 */
export function createOzonBgFailWatch(deps) {
  const { log, notify, reload, alive, probe, suppress } = deps || {}
  const say = (lvl, m) => { try { log && log(lvl, m) } catch (_) {} }
  // Страницы нет только при ЯВНОМ false: у заглушек в проверках этого поля вовсе нет.
  const isAlive = () => { try { return !alive || alive() !== false } catch (_) { return false } }
  let failedAt = 0, failTimer = null, retryTimer = null, step = 0

  /** Снять ожидание целиком (страница доказала, что жива, или её убрали). */
  const stop = () => {
    if (failTimer) { clearTimeout(failTimer); failTimer = null }
    if (retryTimer) { clearTimeout(retryTimer); retryTimer = null }
    failedAt = 0; step = 0
  }

  /** Страница доказала, что она живая. */
  const markAlive = (from) => {
    if (!failedAt) return
    say('INFO', '[ozon-bg] страница поднялась САМА за ' + Math.round((Date.now() - failedAt) / 1000)
      + ' с (доказательство: ' + from + ') — карточку не показываю')
    stop()
  }

  /** Назначить следующую попытку по лестнице пауз. */
  const scheduleRetry = () => {
    if (retryTimer) return                       // попытка уже назначена
    const ms = RETRY_LADDER_MS[step]
    if (ms === undefined) {                      // лестница кончилась — молча долбить Ozon не будем
      say('INFO', '[ozon-bg] больше не пробую загрузить заново: ' + RETRY_LADDER_MS.length + ' попыток подряд не помогли')
      return
    }
    step++
    retryTimer = setTimeout(() => {
      retryTimer = null
      if (!failedAt) { say('TRACE', '[ozon-bg] повтор отменён — страница уже поднялась'); return }
      if (!isAlive()) return                     // страницы нет — трогать нечего
      try { reload && reload(); say('INFO', '[ozon-bg] пробую загрузить страницу заново (попытка ' + step + ' из ' + RETRY_LADDER_MS.length + ', пауза ' + Math.round(ms / 1000) + ' с)') }
      catch (e) { say('WARN', '[ozon-bg] повтор загрузки не удался: ' + ((e && e.message) || e)) }
    }, ms)
  }

  /** Время вышло — решаем, тревожить ли человека. */
  const giveUp = (code) => {
    failTimer = null
    if (!failedAt) return                        // поднялась, пока ждали — карточка не нужна
    if (!isAlive()) { stop(); return }            // страницу убрали — жаловаться не о чем
    const d = decideOzonBgFailNotice({ code, isMainFrame: true, suppress })
    if (d.notify) {
      say('INFO', '[ozon-bg] показал пользователю сообщение о недоступности фоновой страницы (code=' + code
        + ', не поднялась за ' + Math.round(OZON_BG_FAIL_WAIT_MS / 1000) + ' с)')
      notify && notify('Ozon', d.body)
    } else {
      say('INFO', '[ozon-bg] карточку о недоступности НЕ показываю (' + d.reason
        + (d.ageMs ? ', ' + Math.round(d.ageMs / 60000) + ' мин назад' : '') + ', code=' + code + ')')
    }
  }

  return {
    /** Загрузка не удалась. Не жалуемся сразу — ждём и пробуем сами. */
    onFail(code, isMainFrame) {
      // Спрашиваем БЕЗ расхода памяти «уже сообщали» (dryRun): память нужна настоящему
      // решению через 45 секунд, иначе оно всегда отвечало бы «уже сообщали».
      const pre = decideOzonBgFailNotice({ code, isMainFrame, suppress, dryRun: true })
      if (!pre.notify) {
        // Молчание не должно выглядеть как «всё хорошо» — пишем причину в журнал.
        if (code != null && code !== -3) say('INFO', '[ozon-bg] карточку о недоступности НЕ показываю (' + pre.reason + ', code=' + code + ')')
        return
      }
      failedAt = Date.now()
      scheduleRetry()
      if (!failTimer) failTimer = setTimeout(() => giveUp(code), OZON_BG_FAIL_WAIT_MS)
    },

    /**
     * Пришло событие «страница загрузилась». Само по себе это НЕ доказательство
     * (см. ловушку в шапке файла) — спрашиваем у страницы, есть ли в ней содержимое.
     */
    onLoaded() {
      if (!failedAt) return                      // беды нет — и проверять нечего
      let p = null
      try { p = probe && probe() } catch (_) { p = null }
      if (!p || typeof p.then !== 'function') {   // спросить нечем → прежнее правило окна недоверия
        const ms = Date.now() - failedAt
        if (ms < ERROR_PAGE_GRACE_MS) { say('TRACE', '[ozon-bg] «загрузилась» через ' + ms + ' мс после сбоя и спросить страницу нечем — считаю эхом страницы-ошибки'); return }
        markAlive('загрузилась спустя ' + Math.round(ms / 1000) + ' с после сбоя')
        return
      }
      p.then((n) => {
        const nodes = Number(n) || 0
        if (nodes >= OZON_BG_ALIVE_MIN_NODES) { markAlive('на странице ' + nodes + ' элементов'); return }
        say('INFO', '[ozon-bg] «загрузилась», но на странице всего ' + nodes + ' элементов — это заглушка Chromium, а не Ozon; продолжаю ждать')
      }).catch((e) => {
        // Не доказано — значит не засчитываем. Молчать нельзя: иначе не понять, почему ждём дальше.
        say('WARN', '[ozon-bg] не удалось спросить страницу о содержимом: ' + ((e && e.message) || e) + ' — продолжаю ждать')
      })
    },

    /** Сторож прислал данные, которых на пустой странице быть не может. */
    onHookProof() { markAlive('сторож прислал настоящие данные Ozon') },

    stop,
  }
}
