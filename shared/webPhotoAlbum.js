/** Префикс идентификатора: по нему окно уведомления узнаёт «готовое веб-фото». */
export const WEB_PHOTO_ALBUM_PREFIX = 'single_web_'

/** Ширина, до которой ужимаем снимок перед отправкой в окно (больше карточке не нужно). */
export const WEB_PHOTO_MAX_WIDTH = 480

/**
 * Собрать поле `album` для карточки уведомления из готовой картинки.
 *
 * @param {string} dataUrl — картинка целиком (строка вида `data:image/...`)
 * @param {string} key — что-нибудь уникальное для этой карточки (id мессенджера + время)
 * @returns {object|null} объект album или null, если картинки нет / она не картинка
 */
export function buildWebPhotoAlbum(dataUrl, key) {
  if (typeof dataUrl !== 'string' || dataUrl.indexOf('data:image') !== 0) return null
  const id = WEB_PHOTO_ALBUM_PREFIX + (String(key || '').trim() || String(Date.now()))
  return {
    id,
    chatId: '',            // у веб-фото нет чата TDLib — клик по плитке отключён префиксом
    tileThumb: dataUrl,    // это и есть итоговая картинка, догружать нечего
    tileMessageId: null,
    tileText: null,
  }
}

/** Это «готовое веб-фото»? (та же проверка продублирована в окне уведомления — там нет импортов) */
export function isWebPhotoAlbumId(id) {
  return String(id || '').indexOf(WEB_PHOTO_ALBUM_PREFIX) === 0
}
