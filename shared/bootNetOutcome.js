/**
 * v1.2.473 — ИТОГ обращения к окну переподключения ВСЕГДА попадает в журнал.
 *
 * ── ЗАЧЕМ (реальный случай 2026-09-16) ───────────────────────────────────────
 * Пользователь увидел красный экран «Ошибка рендера: Failed to fetch dynamically
 * imported module». В журнале нашлись строка сбоя сети (`net::ERR_NETWORK_CHANGED`,
 * семь запросов умерли в одну секунду) и строка `[BOOT] RENDER ERROR` — и всё.
 * Ни одной строки `[boot-net]` не было НИ в текущем журнале, НИ в прошлом.
 *
 * То есть по журналу нельзя было отличить три разные беды:
 *   1) «пульта» окна переподключения в окне нет вовсе (скрипт не выполнился);
 *   2) пульт есть, но текст ошибки не опознан как сбой загрузки;
 *   3) пульт есть, ошибку опознал, но показывать окно было негде.
 * Это ровно та болезнь, которую проект уже лечил дважды: защита, которая пишет
 * в журнал ТОЛЬКО когда сработала, при отказе выглядит как «всё хорошо»
 * (v1.2.462 — защита от повторов, v1.2.466 — отказы окна переподключения).
 *
 * ── ПОЧЕМУ ЗАПИСЬ ЖИВЁТ ЗДЕСЬ, А НЕ ВНУТРИ ПУЛЬТА ────────────────────────────
 * Сам пульт и есть подозреваемый: если его в окне не оказалось, он и не напишет
 * о себе ничего. Поэтому итог пишет ВЫЗЫВАЮЩАЯ сторона — перехватчик ошибок
 * отрисовки, который к этому моменту уже точно работает (он же записал саму
 * ошибку). Канал тот же, что у всего интерфейса: `app:log` (правило проекта —
 * никаких console.* в `src/`).
 *
 * ── ПОЧЕМУ В shared/, А НЕ В КАЖДОМ ПЕРЕХВАТЧИКЕ ─────────────────────────────
 * Перехватчика два (корневой в `src/main.jsx` и панельный в
 * `src/components/ErrorBoundary.jsx`), а у интерфейса общий бюджет строк.
 * Одна общая функция = по одной строке в каждом месте вместо дубля.
 */

/**
 * Позвать окно переподключения и ЗАПИСАТЬ, чем дело кончилось.
 *
 * @param {object} win — объект окна (передаётся, чтобы функцию можно было проверить)
 * @param {string} message — текст ошибки отрисовки
 * @param {{soft?: boolean, where?: string}} [opts]
 *        soft  — упала отдельная панель (программа жива → без авто-перезагрузки)
 *        where — где случилось (для журнала): «корень» либо имя панели
 * @returns {string} короткий итог — он же уходит в журнал
 */
export function reportBootNetOutcome(win, message, opts) {
  const o = opts || {}
  const where = o.where || 'корень'
  const short = String(message || '').slice(0, 80)
  let outcome
  try {
    const api = win && win.__ccBootNet
    if (!api || typeof api.onLoadError !== 'function') {
      // Самый важный случай: раньше он был НЕВИДИМ — окна нет, и никто не узнает.
      outcome = 'окна переподключения в этом окне НЕТ (пульт не найден)'
    } else {
      outcome = api.onLoadError(message, o.soft ? { soft: true } : undefined)
        ? (o.soft ? 'окно показано без авто-перезагрузки' : 'окно переподключения показано')
        : 'окно НЕ показано (причина — в строке [boot-net] выше)'
    }
  } catch (e) {
    outcome = 'обращение к окну переподключения упало: ' + ((e && e.message) || e)
  }
  const line = '[BOOT] экран ошибки (' + where + '): ' + outcome + ' — «' + short + '»'
  try { win && win.api && win.api.send && win.api.send('app:log', { level: 'ERROR', message: line }) } catch (_) { /* журнал недоступен — молчим, ронять окно нельзя */ }
  return outcome
}
