// shared/ozonTabCount.js — v1.2.505
//
// ГОТОВОЕ ЧИСЛО НОВЫХ, которое Ozon САМ печатает на странице, вместо подсчёта строк таблицы.
//
// ЗАЧЕМ. Счётчик «Отзывы» показывал 5, когда новых 13. Разбор (features.md v1.2.502-505):
// программа считала строки, которые Ozon успел нарисовать, а список он отдаёт ПОРЦИЯМИ — внизу
// кнопка «Показать ещё». Невидимую фоновую страницу никто не листает, поэтому она навсегда
// оставалась на первой порции: 248 проверок подряд ровно 6 строк. Разведка 2026-09-25 нашла путь
// лучше любого листания: на странице стоят вкладки-фильтры со своими счётчиками —
// «Все · Новые 13 · Просмотренные · Обработанные». Число 13 сошлось трижды: надпись на странице =
// подсчёт открытой вкладки = то, что человек видел на значке.
//
// 🔴 ПЕРЕПИСАНО В v1.2.505 ПОСЛЕ РЕВЬЮ. Первая версия (v1.2.504) искала подпись «Новые» ГДЕ УГОДНО
// на странице и поднималась на три уровня вверх за числом. Ревью нашло два способа её обмануть,
// оба воспроизведены:
//   • в таблице отзывов есть бейдж статуса «Новый» — в журнале пользователя он стоит рядом с «0».
//     Встреться он раньше полосы вкладок — на значок ушёл бы 0 при 13 новых;
//   • соседний элемент, содержащий ТОЛЬКО число, склеивался с подписью в тексте общего предка
//     («Новые» + «13» = «Новые13») и отдавал чужое число.
// Теперь ищем не подпись, а ПОЛОСУ ВКЛАДОК: место, где рядом стоят минимум ДВЕ разные подписи из
// набора. Всё, что вне полосы, не рассматривается вовсе — бейдж из таблицы попасть не может.
//
// ПОЧЕМУ ЭТОТ КОД НЕ В СТОРОЖЕ (main/preloads/hooks/ozon.hook.js): сторож занимает 298 строк из
// 300, а разбить его нельзя — он впрыскивается в чужую страницу одним куском, и механизма склейки
// частей в проекте пока нет (TODO-64). Поэтому опрос живёт отдельно и выполняется тем же способом:
// скрипт отправляется в страницу из src/utils/ozonBgWatcher.js. Сторож не тронут, уведомления Ozon
// не задеты вовсе.
//
// ТОЛЬКО ЧТЕНИЕ: скрипт ничего не нажимает и не прокручивает — читает подписи вкладок.

/** Подписи вкладок-фильтров Ozon (разделы «Отзывы» и «Вопросы»), нижним регистром. */
const TAB_LABELS = ['все', 'новые', 'новое', 'новый', 'просмотренные', 'просмотрено',
  'обработанные', 'обработано', 'ждут ответа', 'без ответа']

/**
 * Подписи вкладки «новых». 🔴 Ревью v1.2.505: раньше выбор шёл по `/^Новы/i` — под него НЕ подходит
 * «Новое» (`Ново` ≠ `Новы`), а именно так подписана вкладка в разделе «Вопросы». Список явный,
 * чтобы такой промах нельзя было повторить незаметно.
 */
const NEW_LABELS = ['новые', 'новое', 'новый']

/** Сколько ждать ответа страницы (мс). Чтение подписей — работа на миллисекунды, но страница может быть занята. */
export const TAB_COUNT_TIMEOUT_MS = 10000

/** Потолок обхода страницы. Настоящие страницы Ozon — около 5200 элементов, запас двукратный. */
const SCAN_LIMIT = 12000

/**
 * Скрипт, читающий полосу вкладок ВНУТРИ страницы Ozon.
 * Возвращает `{ path, strip, tabs: [{ label, raw }], truncated }`, где
 *   strip — найдена ли сама полоса вкладок (без неё числу верить нельзя),
 *   raw   — текст числа у вкладки («13», «999+») либо null, если счётчика нет.
 *
 * Как ищет:
 *  1) кандидаты — элементы, чей СОБСТВЕННЫЙ текст (без текста вложенных) равен подписи вкладки.
 *     Собственный, а не общий: частая вёрстка `<div>Новые<span>13</span></div>` подписи-листа не
 *     имеет вовсе, и прежняя версия её не находила (ревью v1.2.505);
 *  2) полоса — ближайший предок, внутри которого лежат минимум ДВЕ РАЗНЫЕ подписи;
 *  3) вкладка — самый большой предок подписи, внутри которого она всё ещё ОДНА;
 *  4) число — только из текста этой вкладки, слева или справа от подписи.
 */
export const OZON_TAB_COUNT_SCRIPT = `(function () {
  var out = { path: location.pathname, strip: false, tabs: [], truncated: false };
  try {
    var LABELS = ${JSON.stringify(TAB_LABELS)};
    function norm(s) { return String(s == null ? '' : s).replace(/\\s+/g, ' ').trim(); }
    function txt(el) { try { return norm(el.textContent); } catch (_) { return ''; } }
    function ownText(el) {
      var s = '';
      for (var n = el.firstChild; n; n = n.nextSibling) if (n.nodeType === 3) s += n.nodeValue;
      return norm(s);
    }
    var all = document.querySelectorAll('*');
    out.truncated = all.length > ${SCAN_LIMIT};
    var cand = [];
    for (var i = 0; i < all.length && i < ${SCAN_LIMIT} && cand.length < 60; i++) {
      var t0 = ownText(all[i]);
      if (t0 && t0.length <= 20 && LABELS.indexOf(t0.toLowerCase()) >= 0) cand.push({ el: all[i], key: t0.toLowerCase(), label: t0 });
    }
    if (cand.length < 2) return out;
    function uniqInside(node) {
      var seen = {}, n = 0;
      for (var k = 0; k < cand.length; k++) {
        var e = cand[k].el;
        if (e !== node && !node.contains(e)) continue;
        if (!seen[cand[k].key]) { seen[cand[k].key] = 1; n++; }
      }
      return n;
    }
    // Полоса = САМАЯ ТЕСНАЯ группа, где рядом стоят минимум две разные подписи.
    // 🔴 Почему «самая тесная», а не «первая попавшаяся»: у любой страницы есть общий предок,
    // содержащий вообще всё — и полосу вкладок, и таблицу с бейджем «Новый». Взяв первого такого
    // предка, мы объявили бы полосой весь документ, и бейдж из таблицы снова считался бы вкладкой
    // (поймано тестом при ревью v1.2.505). Настоящая полоса вкладок — короткая, поэтому берём ту
    // группу, в которой меньше всего текста.
    var strip = null, stripLen = Infinity;
    for (var c = 0; c < cand.length; c++) {
      var p = cand[c].el.parentElement;
      for (var up = 0; up < 8 && p; up++) {
        if (uniqInside(p) >= 2) {
          var len = txt(p).length;
          if (len < stripLen) { stripLen = len; strip = p; }
          break;
        }
        p = p.parentElement;
      }
    }
    // Даже самая тесная группа оказалась огромной → это не полоса вкладок, а кусок страницы.
    if (!strip || stripLen > 300) return out;
    out.strip = true;
    var used = {};
    for (var j = 0; j < cand.length; j++) {
      var it = cand[j];
      if (it.el !== strip && !strip.contains(it.el)) continue;
      if (used[it.key]) continue;
      used[it.key] = 1;
      var cell = it.el, q = it.el.parentElement, depth = 0;
      while (q && q !== strip && depth < 8 && uniqInside(q) === 1) { cell = q; q = q.parentElement; depth++; }
      var t = txt(cell), raw = null;
      if (t.length <= 40) {
        var m = t.match(/^(.+?)\\s*(\\d[\\d\\s]*\\+?)$/);
        if (m && norm(m[1]).toLowerCase() === it.key) raw = m[2].replace(/\\s+/g, '');
        if (raw === null) {
          var m2 = t.match(/^(\\d[\\d\\s]*\\+?)\\s*(.+)$/);
          if (m2 && norm(m2[2]).toLowerCase() === it.key) raw = m2[1].replace(/\\s+/g, '');
        }
      }
      out.tabs.push({ label: it.label, raw: raw });
    }
  } catch (e) { out.error = (e && e.message) || String(e); }
  return out;
})()`

/** Число из текста счётчика: «13» → 13, «999+» → 999, мусор и отрицательные → null. */
function parseCount(raw) {
  if (typeof raw !== 'string' || !raw) return null
  if (/^\s*-/.test(raw)) return null // ревью v1.2.505: «-3» превращалось в 3
  const n = parseInt(raw.replace(/\D+/g, ''), 10)
  return Number.isFinite(n) && n >= 0 ? n : null
}

/**
 * Сколько НОВЫХ записей в разделе — по полосе вкладок.
 *
 * 🔴 ГЛАВНАЯ ЛОВУШКА: Ozon НЕ рисует счётчик у вкладки, когда он равен нулю. Значит «подпись есть,
 * числа нет» — это либо честный ноль, либо «мы смотрим не туда». В v1.2.504 различали по соседям:
 * ноль засчитывался, только если число нашлось хоть у одной другой вкладки. Ревью доказало, что
 * на настоящей странице «Отзывы» число есть ТОЛЬКО у «Новые» (`Все=— Новые=13 Просмотренные=—`),
 * поэтому при прочтении всех отзывов чисел не оставалось ни у кого → возвращалось «не знаю» →
 * значок НИКОГДА не гас. Теперь признак другой и надёжный: найдена сама ПОЛОСА вкладок (в ней
 * минимум две разные подписи). Раз полоса настоящая и вкладка «новых» в ней есть без счётчика —
 * это честный ноль.
 *
 * @param {{strip?: boolean, tabs?: Array<{label: string, raw: string|null}>}|null} res
 * @returns {{ n: number, label: string }|null} null = число со страницы получить не удалось
 */
export function pickOzonTabCount(res) {
  if (!res || res.strip !== true) return null
  const tabs = Array.isArray(res.tabs) ? res.tabs : null
  if (!tabs || !tabs.length) return null
  const hit = tabs.find(t => t && typeof t.label === 'string' && NEW_LABELS.indexOf(t.label.toLowerCase()) >= 0)
  if (!hit) return null
  const n = parseCount(hit.raw)
  return { n: n === null ? 0 : n, label: hit.label }
}

/**
 * Сколько записей в разделе ВСЕГО — по вкладке «Все».
 *
 * v1.2.507. Зачем: значок «Вопросы» показывает, сколько вопросов БЕЗ ОТВЕТА, но сторож видит только
 * первую порцию списка (Ozon отдаёт по десять, дальше кнопка «Показать ещё»). Чтобы честно сказать
 * «их как минимум столько», нужно знать, длиннее ли список видимого куска. Это и говорит «Все».
 * Ozon при большом количестве пишет заглушку «999+» — она разбирается как 999, и этого достаточно.
 *
 * @returns {number|null} null = вкладки «Все» нет или полоса вкладок не найдена
 */
export function pickOzonTabTotal(res) {
  if (!res || res.strip !== true) return null
  const tabs = Array.isArray(res.tabs) ? res.tabs : null
  if (!tabs || !tabs.length) return null
  const hit = tabs.find(t => t && typeof t.label === 'string' && t.label.toLowerCase() === 'все')
  if (!hit) return null
  return parseCount(hit.raw)
}

/** Короткая строка для журнала: что именно прочитали со страницы. */
export function formatOzonTabs(res) {
  if (!res || typeof res !== 'object') return 'страница ничего не вернула'
  const tabs = Array.isArray(res.tabs) ? res.tabs : []
  if (res.strip !== true) return 'полоса вкладок не найдена' + (res.truncated ? ' (страница слишком большая)' : '')
  if (!tabs.length) return 'полоса найдена, но вкладок в ней нет'
  // ревью v1.2.505: битый элемент списка больше не роняет запись в журнал
  return tabs.map(t => (t && t.label ? t.label : '?') + '=' + (t && t.raw != null ? t.raw : '—')).join(' | ')
}
