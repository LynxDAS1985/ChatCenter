/**
 * v1.2.475 — СКОЛЬКО ЖДАТЬ «богатую» версию сообщения, прежде чем показать бедную.
 *
 * ── ЗАЧЕМ ─────────────────────────────────────────────────────────────────────
 * У веб-мессенджеров одно сообщение ловят несколько независимых наблюдателей.
 * Они дают РАЗНОЕ качество данных:
 *   • быстрый наблюдатель — только текст, имя отправителя берётся из кэша;
 *   • наблюдатель списка чатов («богатая» версия) — имя, номер сообщения, ссылка
 *     на фото отправителя, но приходит ПОЗЖЕ.
 * Поэтому быстрый путь перед показом ждёт богатую версию: пришла — показываем её
 * и лишней карточки не будет, не пришла — показываем что есть.
 *
 * ── ЧТО БЫЛО НЕ ТАК (жалоба 2026-09-17) ──────────────────────────────────────
 * Ожиданий было ДВА, с разными сроками, заданными в разных файлах:
 *   • `webviewSetup.js` (быстрый путь) — 500 мс;
 *   • `consoleMessageHandler.js` (запасной путь) — 1200 мс для МАКСа, 200 прочим.
 * Богатая версия МАКСа приходит примерно через секунду — то есть ПОСЛЕ 500 мс,
 * но ДО 1200 мс. Быстрый путь сдавался первым и показывал свою карточку, а следом
 * приходила богатая и показывала вторую. Журнал 15:25:04 это и зафиксировал:
 * `IPC fallback | __CC_NOTIF__ не пришёл за 500мс`, а сразу за ним — богатая копия.
 *
 * Склейка таких пар сделана отдельно (v1.2.474, `notifDedupDecision.js`), но она
 * лечит СЛЕДСТВИЕ. Здесь убирается сама причина разъезда: срок ожидания один и
 * задан в ОДНОМ месте.
 *
 * ── ПОЧЕМУ ПРОЧИЕ МЕССЕНДЖЕРЫ НЕ ТРОГАЕМ ─────────────────────────────────────
 * У них богатая версия приходит быстро, и свои сроки (500 мс у быстрого пути,
 * 200 мс у запасного) подобраны под них. Поэтому функция меняет срок ТОЛЬКО для
 * МАКСа, а остальным возвращает их собственный, привычный.
 */

/** Сколько ждать богатую версию у МАКСа (у него она приходит примерно через секунду). */
export const MAX_ENRICH_WAIT_MS = 1200

/**
 * Сколько ждать богатую версию сообщения перед показом бедной.
 *
 * @param {string} url — адрес страницы мессенджера
 * @param {number} defaultMs — срок этого пути для всех остальных мессенджеров
 * @returns {number} миллисекунды
 */
export function enrichWaitMsFor(url, defaultMs) {
  // Проверка по хосту, а не по подстроке: узкое `/max\.ru/` ловило бы climax.ru
  // и formax.ru (реальная грабля проекта, v1.2.418).
  return isMaxUrl(url) ? MAX_ENRICH_WAIT_MS : defaultMs
}

/** Это страница веб-МАКСа? */
export function isMaxUrl(url) {
  return /web\.max\.ru/i.test(String(url || ''))
}

/**
 * Запас поверх срока ожидания: насколько СВЕЖЕЙ считается уже показанная карточка,
 * когда быстрый путь проверяет «а не показал ли кто-то это сообщение вместо меня».
 */
export const HANDLED_GRACE_MS = 1000

/**
 * Окно проверки «это сообщение уже показано».
 *
 * ── ЗАЧЕМ ФУНКЦИЯ, А НЕ ЧИСЛО ─────────────────────────────────────────────────
 * Раньше окно было зашито числом 1500 мс, когда ожидание богатой версии равнялось
 * 500 мс — то есть запас был 1000 мс. В v1.2.475 ожидание у МАКСа выросло до
 * 1200 мс, а окно осталось 1500 → запас усох до 300 мс. Арифметика: богатая копия,
 * показанная всего на 400 мс раньше проверки, даёт возраст 1600 мс > 1500 —
 * проверка её НЕ видит и выпускает ВТОРУЮ карточку. Ровно тот дубль, который
 * v1.2.474–475 и убирали. Поэтому окно считается ОТ срока ожидания.
 *
 * @param {number} waitMs — сколько этот путь ждал богатую версию
 * @returns {number} миллисекунды
 */
export function alreadyHandledWindowMs(waitMs) {
  const wait = Number(waitMs)
  return (Number.isFinite(wait) && wait > 0 ? wait : 0) + HANDLED_GRACE_MS
}
