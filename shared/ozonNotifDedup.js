/** Сколько помним показанное (6 часов: рабочая смена оператора) */
export const OZON_DEDUP_TTL = 6 * 60 * 60 * 1000
/** Потолок записей — чтобы память не росла бесконечно */
export const OZON_DEDUP_MAX = 500
/** Разделы со СПИСКОВОЙ природой (постоянная личность записи) */
export const OZON_DEDUP_SOURCES = ['ozon-questions', 'ozon-reviews']

/** ключ → когда показывали (мс). Живёт в приложении, переживает перезагрузку страницы. */
const seen = new Map()

/**
 * Ключ записи. Приоритет — отпечаток от хука (`g`/`tag`, напр. `ozon-q:-100455210`),
 * запасной путь — раздел + текст (если хук почему-то не прислал отпечаток).
 * @returns {string}
 */
export function ozonNotifKey(source, tag, body) {
  const t = String(tag || '').trim()
  if (t) return t
  return String(source || '') + '|' + String(body || '').trim().slice(0, 200)
}

/**
 * Показывать ли это уведомление фоновой страницы Ozon?
 *
 * @param {string} source — `ozon-questions` | `ozon-reviews` | `ozon-list` | …
 * @param {string} tag — отпечаток от хука (поле `g`)
 * @param {string} body — текст
 * @param {number} [now] — текущее время (для тестов)
 * @param {number} [ttl] — окно памяти (для тестов)
 * @returns {{skip: boolean, reason: string, ageMs: number}}
 *          skip=true → это повтор, показывать НЕ надо (reason объясняет почему).
 *
 * Крайние случаи: раздел не списковый → никогда не подавляем (skip=false,
 * reason='не списковый раздел'); пустые аргументы → ключ всё равно строится
 * (source|body), поэтому пустое уведомление подавится как повтор самого себя.
 */
export function shouldSkipOzonNotif(source, tag, body, now = Date.now(), ttl = OZON_DEDUP_TTL) {
  if (OZON_DEDUP_SOURCES.indexOf(String(source || '')) === -1) {
    return { skip: false, reason: 'не списковый раздел', ageMs: 0 }
  }
  const key = ozonNotifKey(source, tag, body)
  const at = seen.get(key)
  if (at !== undefined && now - at < ttl) {
    return { skip: true, reason: 'уже показывали', ageMs: now - at }
  }
  seen.set(key, now)
  // чистка: сначала просроченные, если всё равно много — самые старые
  if (seen.size > OZON_DEDUP_MAX) {
    for (const [k, v] of seen) { if (now - v >= ttl) seen.delete(k) }
    while (seen.size > OZON_DEDUP_MAX) { seen.delete(seen.keys().next().value) }
  }
  return { skip: false, reason: at === undefined ? 'впервые' : 'память устарела', ageMs: at === undefined ? 0 : now - at }
}

/** Только для тестов: очистить память. */
export function resetOzonNotifDedup() { seen.clear() }
