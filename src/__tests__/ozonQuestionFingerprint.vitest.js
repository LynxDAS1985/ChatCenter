// v1.2.437: тест «отпечатка» вопроса Ozon и памяти показанного.
//
// 🔴 ЛОВУШКА НА РЕАЛЬНУЮ ЖАЛОБУ (2026-09-09): «почему уведомления одно и то же
// повторяется каждую минуту». Один и тот же вопрос Ozon («Ремень генератора Gates…»)
// приходил карточкой в 14:28:36, 14:29:36, 14:30:37, 14:31:36, 14:32:37, 14:33:36…
//
// КОРЕНЬ (доказан чтением сохранённой памяти страницы с диска): отпечаток вопроса
// считался как хеш от «товар|текст вопроса», а товар берётся ПОЗИЦИОННО — 2-я ссылка
// в строке таблицы. Между перезагрузками фоновой страницы (она обновляется раз в минуту)
// 2-я ссылка могла указывать на другой элемент → отпечаток того же вопроса менялся →
// он выглядел новым. В сохранённой памяти было видно: три отпечатка стоят на месте,
// четвёртый меняется (-240107430 → 2077912008 → -1534851191).
// Вторая половина корня: память ЗАМЕНЯЛАСЬ текущим набором (`_qPrev = cur`), поэтому
// прежний отпечаток выбрасывался и петля не заканчивалась никогда.
//
// Тест читает РЕАЛЬНЫЙ файл хука (не копию), вытаскивает из него функцию хеша и
// проверяет поведение + сторожит сами строки фикса.
import { describe, it, expect } from 'vitest'
import fs from 'node:fs'

const SRC = fs.readFileSync('main/preloads/hooks/ozon.hook.js', 'utf8')

/** Достаём настоящую функцию _hash из кода хука и делаем её вызываемой */
function realHash() {
  // в хуке она записана В ОДНУ строку — берём её целиком до конца строки
  const m = SRC.match(/function _hash\(s\)\s*\{[^\n]*\}/)
  expect(m, 'функция _hash не найдена в хуке — тест устарел').toBeTruthy()
  return new Function(`${m[0]}; return _hash`)()
}

describe('Отпечаток вопроса Ozon', () => {
  const hash = realHash()

  it('одинаковый текст вопроса → одинаковый отпечаток', () => {
    const q = 'На гранту 2015 года 8 клоп с наияжителем и кондиционером подойдёт ли данный ремень?'
    expect(hash(q)).toBe(hash(q))
  })

  it('🔴 ЛОВУШКА: отпечаток НЕ должен зависеть от названия товара', () => {
    // Именно из-за товара в отпечатке вопрос уведомлял каждую минуту.
    const q = 'На гранту 2015 года 8 клоп с наияжителем и кондиционером подойдёт ли данный ремень?'
    const withProductA = hash('Ремень генератора Gates (100% оригинал)' + '|' + q)
    const withProductB = hash('Магазин Автолибер' + '|' + q)
    expect(withProductA).not.toBe(withProductB)   // старый способ был нестабилен — вот доказательство
    expect(hash(q)).toBe(hash(q))                 // новый способ стабилен
  })

  it('разные вопросы → разные отпечатки (не склеиваем чужие)', () => {
    expect(hash('Подойдёт ли этот ремень?')).not.toBe(hash('А какая длина ремня?'))
  })

  it('пустой текст не ломает функцию', () => {
    expect(typeof hash('')).toBe('number')
  })
})

describe('Строки фикса на месте (сторож исходника)', () => {
  it('отпечаток берётся ТОЛЬКО из текста вопроса', () => {
    expect(SRC).toMatch(/var fp = _hash\(info\.qText\)/)
    // старая форма «товар|вопрос» должна быть удалена
    expect(SRC).not.toMatch(/_hash\(\(info\.product \|\| ''\) \+ '\|' \+ info\.qText\)/)
  })

  it('память ДОПОЛНЯЕТСЯ, а не заменяется', () => {
    expect(SRC).toMatch(/_qPrev = Object\.assign\(_qPrev \|\| \{\}, cur\)/)
    expect(SRC).not.toMatch(/\{ _qPrev = cur; _saveSeen\('__ccOzonQSeen', cur\); \}/)
  })

  it('у памяти есть потолок (не растёт бесконечно)', () => {
    expect(SRC).toMatch(/Object\.keys\(_qPrev\)\.length > 300/)
  })

  it('память сохраняется под тем же ключом (переживает перезагрузку)', () => {
    expect(SRC).toMatch(/_saveSeen\('__ccOzonQSeen', _qPrev\)/)
    expect(SRC).toMatch(/_loadSeen\('__ccOzonQSeen'\)/)
  })
})
