// v1.2.482 — WhatsApp: строка чата на миг показывает СТАТУС вместо текста сообщения.
//
// ЗАЧЕМ ПРОВЕРКА. Перехватчик WhatsApp помнит «последний текст» каждого чата и шлёт уведомление,
// когда текст ИЗМЕНИЛСЯ. Если принять за текст статус («печатает…», «в сети»), происходит ДВЕ беды
// подряд: (1) показывается ложная карточка со словом «печатает»; (2) статус попадает в память, и
// когда вернётся НАСТОЯЩИЙ текст сообщения — он снова окажется «изменившимся» и уедет ВТОРОЙ
// карточкой. Ровно эта болезнь (одно сообщение — несколько карточек) подтверждена у ВКонтакте
// 2026-09-18 и у Ozon в v1.2.437; здесь она закрыта заранее, по чтению кода.
//
// Проверка достаёт НАСТОЯЩИЙ список масок из файла перехватчика (не копию) и прогоняет его на
// живых примерах — приём проекта, как в ozonQuestionFingerprint.vitest.js.
import { describe, it, expect } from 'vitest'
import fs from 'node:fs'

const HOOK = fs.readFileSync('main/preloads/hooks/whatsapp.hook.js', 'utf8')

/** Достаём реальную маску «это статус, а не сообщение» и повторяем ту же очистку хвоста, что в хуке. */
function realStatusCheck() {
  const m = HOOK.match(/var _waStatusOnly = (\/.+\/i);/)
  expect(m, 'маска статусов не найдена — тест устарел').toBeTruthy()
  const re = new Function(`return ${m[1]}`)()
  return (text) => re.test(String(text).replace(/[.…\s]+$/, ''))
}

describe('WhatsApp: статус не принимается за сообщение', () => {
  const isStatus = realStatusCheck()

  it('типичные статусы отсеиваются', () => {
    for (const s of ['печатает…', 'печатает...', 'Печатает', 'набирает текст', 'записывает аудио',
      'в сети', 'онлайн', 'online', 'typing…', 'recording audio', 'last seen recently']) {
      expect(isStatus(s), `должно считаться статусом: ${s}`).toBe(true)
    }
  })

  it('[!] ЛОВУШКА: живое сообщение со словом «печатает» НЕ теряется', () => {
    for (const s of ['я уже печатаю письмо', 'он печатает медленно', 'Привет', 'В сети магазина акция',
      'Онлайн-запись открыта', 'печатает отчёт по продажам']) {
      expect(isStatus(s), `должно считаться сообщением: ${s}`).toBe(false)
    }
  })

  it('[!] ЛОВУШКА: маска проверяет строку ЦЕЛИКОМ (иначе съест пол-переписки)', () => {
    expect(HOOK).toMatch(/var _waStatusOnly = \/\^\(/)   // начинается с ^(
    expect(HOOK).toMatch(/\)\$\/i;/)                      // заканчивается )$/i
  })

  it('[!] ЛОВУШКА: проверка стоит ДО записи в память — иначе статус её отравит', () => {
    const iCheck = HOOK.indexOf('_waStatusOnly.test(')
    const iMem = HOOK.indexOf("var prev = _lastSidebarTexts[chatName]")
    expect(iCheck).toBeGreaterThan(0)
    expect(iCheck).toBeLessThan(iMem)
  })

  it('память чатов по-прежнему ведётся по ИМЕНИ чата (выпавшая строка не забывается)', () => {
    // Отличие от ВК: здесь память не пересобирается каждым проходом, поэтому болезнь ВК тут
    // невозможна — запись живёт до следующего появления той же строки.
    expect(HOOK).toContain('_lastSidebarTexts[chatName] = lastMsg')
    expect(HOOK).not.toMatch(/_lastSidebarTexts\s*=\s*\{\}\s*;?\s*\n\s*(for|rows)/)
  })
})
