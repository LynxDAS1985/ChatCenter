// ЗАЧЕМ. Сторож (`main/preloads/hooks/<тип>.hook.js`) впрыскивается в страницу мессенджера ОДНИМ
// куском и импортов иметь не может — значит разбить его на модули нельзя, только склеить из частей.
// Три сторожа уже стоят вплотную к своему потолку (300 строк), и следующая правка любого из них
// упрётся. Механизм склейки добавлен в v1.2.509.
//
// 🔴 ГЛАВНАЯ ОПАСНОСТЬ, от которой сторожит этот файл: путей впрыска ДВА и они независимы —
//   • main/preloads/monitor.preload.cjs — вставляет сторожа как <script> (обычные мессенджеры);
//   • main/handlers/mainIpcHandlers.js (app:read-hook) — отдаёт текст окну, которое выполняет его
//     само (Ozon и ВК: их защита блокирует <script> из preload).
// Если склейку добавить только в один путь, страница получит РАЗНЫЙ код в зависимости от того,
// каким путём её впрыснули, — и найти это будет крайне тяжело: половина мессенджеров работает,
// половина молча теряет кусок сторожа.
//
// Запускается как обычный статический тест: node src/__tests__/hookPartsGlue.test.cjs

const fs = require('node:fs')
const path = require('node:path')

const root = path.join(__dirname, '..', '..')
const preload = fs.readFileSync(path.join(root, 'main/preloads/monitor.preload.cjs'), 'utf8')
const mainIpc = fs.readFileSync(path.join(root, 'main/handlers/mainIpcHandlers.js'), 'utf8')

let ok = 0, fail = 0
function check(name, cond, hint) {
  if (cond) { console.log('  ✅ ' + name); ok++ }
  else { console.log('  ❌ ' + name + (hint ? ' — ' + hint : '')); fail++ }
}

console.log('🧪 Склейка частей сторожа чужой страницы (оба пути впрыска)\n')

check('путь 1 (preload) читает вторую часть', /part2\.hook\.js/.test(preload),
  'в monitor.preload.cjs нет чтения <тип>.part2.hook.js — половина мессенджеров потеряет кусок сторожа')
check('путь 2 (app:read-hook) читает вторую часть', /part2\.hook\.js/.test(mainIpc),
  'в mainIpcHandlers.js нет чтения <тип>.part2.hook.js — Ozon и ВК потеряют кусок сторожа')

// Порядок важен: вторая часть объявляет вспомогательные функции, основная их зовёт.
check('путь 1 складывает ВТОРУЮ ЧАСТЬ ВПЕРЁД', /part2\s*\+\s*'\\n;\\n'\s*\+\s*hookCode/.test(preload),
  'основная часть должна идти ПОСЛЕ второй, иначе она позовёт функции, которых ещё нет')
check('путь 2 складывает ВТОРУЮ ЧАСТЬ ВПЕРЁД', /part2\s*\+\s*'\\n;\\n'\s*\+\s*main/.test(mainIpc),
  'тот же порядок, что и в первом пути')

// Отсутствие второй части не должно ничего менять — иначе механизм опасен сам по себе.
check('путь 1: нет второй части → впрыск как раньше', /catch\(e3\)\s*\{\}/.test(preload),
  'чтение второй части обязано молча переживать её отсутствие')
check('путь 2: нет второй части → отдаём только основную', /part2\s*\?\s*part2[^:]*:\s*main/.test(mainIpc),
  'без второй части возвращается ровно основной файл')

// Отчёт о впрыске должен показывать РЕАЛЬНОЕ число склеенных файлов (ADR-071).
check('путь 1 сообщает число склеенных частей', /hookParts\s*=\s*2/.test(preload),
  'без этого потеря куска снова станет невидимой в журнале')
check('путь 2 сообщает число склеенных частей', /частей=\$\{parts\}/.test(mainIpc),
  'в журнале должно быть видно, сколько файлов склеено')

console.log(`\n📊 Результат: ${ok} ✅ / ${fail} ❌ из ${ok + fail}`)
process.exit(fail ? 1 : 0)
